#!/usr/bin/env python3
"""Generate site/results.js from graded evaluation runs.

Every number on the landing page comes from evals/perception/results/graded.jsonl.
site/story.json picks the two runs shown side by side and describes their steps
in plain words; times and outcomes are still read from the graded runs.

    python3 site/build_results.py
"""

from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
GRADED = HERE.parent / "evals" / "perception" / "results" / "graded.jsonl"
STORY = HERE / "story.json"
OUT = HERE / "results.js"

LABELS = {
    ("claude", "sonnet"): "Claude Code · Sonnet",
    ("claude", "haiku"): "Claude Code · Haiku",
    ("codex", "default"): "Codex",
    ("dsh", "default"): "DeepSeek Harness \u00b7 Flash",
}
ORDER = list(LABELS)
# Tasks whose answer is spoken or sits in the 12-minute video; the rest are quick checks.
SPEECH_OR_LONG = {"tutorial-mention", "lecture-password", "lecture-room"}


def find_run(rows: list[dict], ref: dict) -> dict:
    for r in rows:
        if all(r.get(k) == v for k, v in ref.items()):
            return r
    raise SystemExit(f"story run not found: {ref}")


def main() -> None:
    rows = [json.loads(line) for line in GRADED.read_text().splitlines() if line.strip()]
    cells = defaultdict(list)
    for r in rows:
        cells[(r["agent"], r["model"], r["condition"])].append(r)

    table = []
    for agent, model in sorted({(a, m) for a, m, _ in cells}, key=lambda k: ORDER.index(k) if k in ORDER else 99):
        entry = {"label": LABELS.get((agent, model), f"{agent} {model}")}
        for condition in ("baseline", "plugin"):
            runs = cells.get((agent, model, condition), [])
            if runs:
                long_runs = [r["seconds"] for r in runs if r["task"] in SPEECH_OR_LONG]
                quick_runs = [r["seconds"] for r in runs if r["task"] not in SPEECH_OR_LONG]
                entry[condition] = {
                    "passed": sum(r["pass"] for r in runs),
                    "total": len(runs),
                    "long_s": round(statistics.median(long_runs)) if long_runs else None,
                    "quick_s": round(statistics.median(quick_runs)) if quick_runs else None,
                }
        table.append(entry)

    story = json.loads(STORY.read_text()) if STORY.is_file() else None
    if story:
        for side in ("without", "with"):
            run = find_run(rows, story[side]["run"])
            story[side]["seconds"] = round(run["seconds"])
            story[side]["passed"] = run["pass"]

    data = json.dumps({"table": table, "story": story}, ensure_ascii=False, indent=1)
    OUT.write_text(RENDER.replace("__DATA__", data))
    print(f"wrote {OUT}")


RENDER = r"""// Generated by site/build_results.py from evals/perception/results/graded.jsonl. Do not edit.
(function () {
  var DATA = __DATA__;
  var TEXT = {
    en: { agent: "Agent", right: "Right answers", long: "Spoken or long-video questions", quick: "Quick checks",
          s: "s", correct: "Correct", wrong: "Wrong answer",
          hint: "Each cell shows without the plugin, then with it. Times are the median per question." },
    zh: { agent: "Agent", right: "答对", long: "答案在语音或长视频里的问题", quick: "简单检查",
          s: "秒", correct: "答对", wrong: "答错",
          hint: "每格左边是不装插件，右边是装上插件。时间是每道题的中位耗时。" }
  };
  function clock(sec) {
    var m = Math.floor(sec / 60), s = sec % 60;
    return m ? m + ":" + (s < 10 ? "0" : "") + s : s + "s";
  }
  function pair(row, key, fmt) {
    var a = row.baseline, b = row.plugin;
    if (!a || !b) return "<td>–</td>";
    return '<td><span class="num">' + fmt(a[key], a) + '</span><span class="sub"> → </span><span class="num with">' +
      fmt(b[key], b) + "</span></td>";
  }
  window.renderResults = function (lang) {
    var t = TEXT[lang] || TEXT.en;
    var table = document.getElementById("results-table");
    if (table) {
      var secs = function (v) { return v == null ? "–" : v + t.s; };
      var html = "<caption>" + t.hint + "</caption><thead><tr><th>" + t.agent + "</th><th>" + t.right + "</th><th>" +
        t.long + "</th><th>" + t.quick + "</th></tr></thead><tbody>";
      DATA.table.forEach(function (row) {
        html += "<tr><td>" + row.label + "</td>" +
          pair(row, "passed", function (v, c) { return v + "/" + c.total; }) +
          pair(row, "long_s", secs) + pair(row, "quick_s", secs) + "</tr>";
      });
      table.innerHTML = html + "</tbody>";
    }
    var versus = document.getElementById("versus"), note = document.getElementById("versus-note");
    if (versus && DATA.story) {
      var s = DATA.story;
      versus.innerHTML = ["without", "with"].map(function (side) {
        var v = s[side], copy = v[lang] || v.en;
        return '<div class="run ' + side + '"><h3>' + copy.title + "</h3>" +
          '<div class="clock">' + clock(v.seconds) + "</div>" +
          "<p>" + (v.passed ? t.correct : t.wrong) + "</p><ol>" +
          copy.steps.map(function (x) { return "<li>" + x + "</li>"; }).join("") + "</ol></div>";
      }).join("");
      if (note) note.textContent = (s.note && (s.note[lang] || s.note.en)) || "";
    }
  };
  var lang = (document.documentElement.lang || "en").indexOf("zh") === 0 ? "zh" : "en";
  window.renderResults(lang);
})();
"""

if __name__ == "__main__":
    main()
